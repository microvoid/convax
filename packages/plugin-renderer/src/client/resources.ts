/** Resource addresses keep directory and preview loading in the Client resource model. */
import type { CanvasDirectory, CanvasDocumentPreview, CanvasPreview, CanvasResource, CanvasWorkspace } from '@deepseek-ai/dsh-convax-plugin-host/types'
import type { SessionReference } from '@deepseek-ai/dsh-api-session-controller/client'

declare module '@deepseek-ai/dsh-client-ui-slots' {
  interface ResourceProtocolMap {
    /** Complete Host canvas snapshot. */
    'convax-workspace': CanvasWorkspace
    /** Direct children of one provider directory. */
    'convax-directory': CanvasDirectory
    /** Bounded text preview. */
    'convax-preview': CanvasPreview
    /** Lightweight metadata for a file or folder card. */
    'convax-resource': CanvasResource
    /** Complete, versioned document bytes for shared preview renderers. */
    'convax-document': CanvasDocumentPreview
    /** Retained DSH Session owned by one mounted Conversation occurrence. */
    'convax-thread': { reference: SessionReference }
  }
}

/**
 * Encode a resource path without relying on its path separator syntax.
 * @param protocol - Registered Client resource protocol.
 * @param path - Provider process path; empty means no resource is selected.
 * @returns Resource address, or an empty string for no selection.
 */
export function resourceAddress(protocol: string, path: string): string {
  return path === '' ? '' : `dsh-resource://${protocol}/${encodeURIComponent(path)}`
}

/**
 * Extract the provider key from an address generated by this package.
 * @param address - Encoded resource address.
 * @returns Original provider path.
 */
export function resourcePath(address: string): string {
  return decodeURIComponent(new URL(address).pathname.slice(1))
}
